import assert from "node:assert/strict";
import { test } from "node:test";
import { compareSharedLocks } from "./check-shared-rust-locks.mjs";

const packageText = (version = "1.0.0", checksum = "abc", source = "registry+https://github.com/rust-lang/crates.io-index") => `[[package]]\nname = "collector"\nversion = "${version}"\nsource = "${source}"\nchecksum = "${checksum}"\n`;
const lock = text => `# Generated by Cargo\nversion = 4\n\n${text}`;
test("permits root-only test dependencies and local engine package", () => {
  assert.deepEqual(compareSharedLocks(lock(packageText() + packageText("2.0.0")), lock(packageText() + '[[package]]\nname = "sd300-engine"\nversion = "4.0.0"\n')), []);
});
test("rejects changed shared version, registry and checksum", () => {
  const root = lock(packageText());
  for (const candidate of [packageText("1.0.1"), packageText("1.0.0", "changed"), packageText("1.0.0", "abc", "registry+https://example.invalid")]) {
    assert.equal(compareSharedLocks(root, lock(candidate)).length, 1);
  }
});
test("rejects malformed lockfiles instead of passing an empty comparison", () => {
  assert.throws(() => compareSharedLocks("not a lock", lock(packageText())));
  assert.throws(() => compareSharedLocks(lock(""), lock(packageText())));
  assert.throws(() => compareSharedLocks(lock(packageText()), lock('[[package]]\nname = "collector"\n')));
});
